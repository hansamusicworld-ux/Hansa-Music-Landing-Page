const fs = require('node:fs');
const assert = require('node:assert/strict');
const yaml = require('js-yaml');
const Ajv2020 = require('ajv/dist/2020').default;
const addFormats = require('ajv-formats');
(async () => {
  const response = await fetch('https://render.com/schema/render.yaml.json', { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error('Official Render Blueprint schema could not be downloaded.');
  const schema = await response.json();
  const blueprint = yaml.load(fs.readFileSync('render.yaml', 'utf8'));
  const ajv = new Ajv2020({ allErrors: true, strict: false }); addFormats(ajv);
  const validate = ajv.compile(schema);
  if (!validate(blueprint)) throw new Error(JSON.stringify(validate.errors, null, 2));
  const web = blueprint.services[0], database = blueprint.databases[0];
  assert.equal(web.type, 'web'); assert.equal(web.runtime, 'node');
  assert.notEqual(web.plan, 'free'); assert.notEqual(database.plan, 'free');
  assert.equal(web.region, database.region);
  assert.equal(web.healthCheckPath, '/api/health');
  assert.equal(web.envVars.find(v => v.key === 'DATABASE_URL').fromDatabase.name, database.name);
  assert.equal(web.envVars.find(v => v.key === 'HANSA_PUBLIC_SITE').value, 'true');
  const password = web.envVars.find(v => v.key === 'HANSA_OWNER_PASSWORD');
  assert.equal(password.sync, false); assert.equal(password.value, undefined);
  assert.deepEqual(database.ipAllowList, []);
  assert.equal(web.ipAllowList, undefined);
  assert.ok(web.preDeployCommand.includes('prepare-production.ts'));
  assert.ok(web.startCommand.includes('$PORT'));
  assert.ok(fs.existsSync('package-lock.json'));
  assert.ok(fs.existsSync('drizzle/meta/_journal.json'));
  console.log('PASS: render.yaml matches the official Render JSON Schema.');
  console.log('PASS: Public web service, private persistent database, secret prompt, automatic migrations, port binding and healthcheck are wired correctly.');
  console.log('Configuration validated only. No hosting resource, bill, domain or public deployment was created.');
})().catch(error => { console.error(error.message); process.exitCode = 1; });
